"""Installable Python apps: a double-click bundle with Python + every dependency inside.

macOS   built here with PyInstaller → <App>.app + <App>-<ver>.dmg
Windows built here with PyInstaller when E2 itself runs on Windows; otherwise on GitHub Actions (windows-latest, free for public repos / within the monthly minutes for private ones)
        → <App>-<ver>-windows.zip holding <App>\\<App>.exe. The zip is parked on a GitHub pre-release
        (release files don't count against the small Actions storage quota) and downloaded back here.
"""
import asyncio
import json
import re
import shutil
import time
from pathlib import Path

from . import tech

WORKFLOW = ".github/workflows/e2-windows.yml"


def entry_point(ws: Path) -> str:
    pp = ws / "pyproject.toml"
    if pp.exists():
        sec = re.search(r"^\[project\.scripts\]\s*\n(.*?)(?:\n\[|\Z)", pp.read_text(errors="ignore"), re.S | re.M)
        if sec:
            m = re.search(r"""^\s*[\w.-]+\s*=\s*["']([\w.]+):([\w.]+)["']""", sec.group(1), re.M)
            if m:
                return f"{m.group(1)}:{m.group(2)}"
    for f in ("main.py", "app.py", "__main__.py"):
        if (ws / f).exists():
            return f"{f[:-3]}:"
    raise RuntimeError("No entry point: add [project.scripts] to pyproject.toml (e.g. myapp = \"myapp.main:run\")")


def package_name(ws: Path) -> str:
    return entry_point(ws).split(":")[0].split(".")[0]


def launcher(ws: Path, cfg: dict, app: str) -> str:
    """Python source of the bundle's start script (same for macOS and Windows)."""
    mod, _, fn = entry_point(ws).partition(":")
    env = {}
    for part in re.split(r"[;\n]+", cfg.get("app_env") or ""):
        k, eq, v = part.strip().partition("=")
        if eq and k.strip():
            env[k.strip()] = v.strip()
    return f'''# Generated by E2: starts {app} from the bundle.
import os, sys, threading, time, webbrowser
from pathlib import Path
APP = {app!r}
if sys.platform == "darwin":
    appdata = Path.home() / "Library" / "Application Support" / APP
elif os.name == "nt":
    appdata = Path(os.environ.get("APPDATA", Path.home())) / APP
else:
    appdata = Path.home() / ".local" / "share" / APP
appdata.mkdir(parents=True, exist_ok=True)
os.chdir(appdata)
for k, v in {json.dumps(env)}.items():
    os.environ.setdefault(k, os.path.expanduser(v.replace("{{appdata}}", str(appdata))))
URL = {(cfg.get("app_url") or "").strip()!r}
if URL:
    threading.Thread(target=lambda: (time.sleep(3), webbrowser.open(URL)), daemon=True).start()
import {mod} as _m
{f"_m.{fn}()" if fn else ""}
'''


ICON_SIZE = 1024


def check_icon(data: bytes, name: str = "icon.png") -> None:
    """The one accepted app icon: a square 1024×1024 PNG. Raises ValueError with a message for the user."""
    import struct
    if not name.lower().endswith(".png") or data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        raise ValueError(f"'{name}' is not a PNG. Please choose a 1024 × 1024 PNG file")
    w, h = struct.unpack(">II", data[16:24])
    if (w, h) != (ICON_SIZE, ICON_SIZE):
        raise ValueError(f"'{name}' is {w} × {h}. The app icon must be exactly 1024 × 1024 pixels (PNG)")


def icon_source(ws: Path, cfg: dict) -> Path | None:
    """The app icon from the checked-out source (default icon.png in the repo root). Must be a 1024×1024 PNG."""
    if not cfg.get("icon"):
        return None
    from .platform import repo_file
    name = (cfg.get("icon_path") or "icon.png").strip()
    p = repo_file(ws, name, "App icon")
    if not p:
        raise RuntimeError(f"App icon: '{name}' not found in the repository. Add a 1024 × 1024 PNG there, or change the file name")
    try:
        check_icon(p.read_bytes(), p.name)
    except ValueError as e:
        raise RuntimeError(f"App icon: {e}")
    return p


async def to_png(ctx, key, src: Path, work: Path, size: int) -> Path:
    """The 1024 PNG scaled down for a target (macOS built-in sips)."""
    work.mkdir(parents=True, exist_ok=True)
    out = work / f"icon-{size}.png"
    await ctx.sh(key, "sips", "-z", str(size), str(size), src, "--out", out, quiet=True)
    return out


async def mac_icns(ctx, key, src: Path, work: Path) -> Path:
    """1024 PNG → .icns with every size macOS wants (16 … 512@2x)."""
    iconset = work / "icon.iconset"
    shutil.rmtree(iconset, ignore_errors=True)
    iconset.mkdir(parents=True)
    for size in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            px = size * scale
            await ctx.sh(key, "sips", "-z", str(px), str(px), src, "--out", iconset / f"icon_{size}x{size}{'@2x' if scale == 2 else ''}.png", quiet=True)
    icns = work / "icon.icns"
    await ctx.sh(key, "iconutil", "-c", "icns", iconset, "-o", icns, quiet=True)
    ctx.log(key, "  app icon: 1024 PNG → icon.icns (macOS)")
    return icns


def pyinstaller_args(ws: Path, app: str, windowed: bool = True) -> list[str]:
    pkg = package_name(ws)
    return ["--noconfirm", "--clean", "--onedir", *(["--windowed"] if windowed else []), "--name", app,
            "--collect-all", pkg, "--paths", "."]


# ── macOS, built on this Mac ──
async def build_mac(ctx, key, ws: Path, out: Path, app: str) -> list[Path]:
    if tech.HOST != "mac":
        raise RuntimeError("macOS apps can only be built on a Mac")
    env = await _pyinstaller_setup(ctx, key, ws)
    b = ws / ".e2build" / "pyapp"
    shutil.rmtree(b, ignore_errors=True)
    b.mkdir(parents=True)
    (b / "launch.py").write_text(launcher(ws, ctx.config["platform"], app))
    icon = icon_source(ws, ctx.config["platform"])
    icon_args = ["--icon", await mac_icns(ctx, key, icon, b / "icon")] if icon else []
    ctx.log(key, "  bundling Python + all dependencies (large ML libraries make this take a few minutes)")
    await ctx.sh(key, "python", "-m", "PyInstaller", *pyinstaller_args(ws, app), "--distpath", b / "dist", "--workpath", b / "work",
                 "--specpath", b, *icon_args, "--osx-bundle-identifier", f"local.e2.{package_name(ws)}", b / "launch.py", cwd=ws, env=env)
    bundle = b / "dist" / f"{app}.app"
    if not bundle.exists():
        raise RuntimeError("PyInstaller did not produce an .app")
    dmg = out / f"{app}-{ctx.run['version']}.dmg"
    ctx.log(key, "  creating the disk image")
    stage = b / "dmg"
    stage.mkdir()
    shutil.move(str(bundle), stage / bundle.name)
    (stage / "Applications").symlink_to("/Applications")  # drag-to-install
    await ctx.sh(key, "hdiutil", "create", "-volname", f"{app} {ctx.run['version']}", "-srcfolder", stage, "-ov", "-format", "UDZO", dmg)
    return [dmg]


# ── Windows, built on GitHub Actions ──
def github_repo(url: str) -> str | None:
    m = re.search(r"github\.com[:/]([^/]+)/([^/]+?)(?:\.git)?/?$", url or "")
    return f"{m.group(1)}/{m.group(2)}" if m else None


def workflow_yaml(ws: Path, cfg: dict, app: str) -> str:
    pyver = "3.12"
    pp = ws / "pyproject.toml"
    if pp.exists():
        m = re.search(r'requires-python\s*=\s*"[><=~^ ]*(\d+\.\d+)', pp.read_text(errors="ignore"))
        pyver = m.group(1) if m else pyver
    launch = launcher(ws, cfg, app).replace("\n", "\n          ")
    args = " ".join(pyinstaller_args(ws, app))
    return f"""# Generated by E2. Builds the Windows app when E2 asks for it (manual dispatch only; never on push).
name: E2 Windows build
on:
  workflow_dispatch:
    inputs:
      version: {{ required: true }}
      ref: {{ required: true }}
      tag: {{ required: true }}
      icon: {{ required: false, default: "" }}
permissions:
  contents: write
jobs:
  windows:
    runs-on: windows-latest
    steps:
      - uses: actions/checkout@v4
        with: {{ ref: "${{{{ inputs.ref }}}}" }}
      - uses: actions/setup-python@v5
        with: {{ python-version: "{pyver}" }}
      - name: Install
        run: |
          python -m pip install --upgrade pip
          python -m pip install . pyinstaller pillow
      - name: Launcher
        shell: python
        run: |
          from pathlib import Path
          Path("e2_launch.py").write_text('''{launch}''')
      - name: Icon
        if: ${{{{ inputs.icon != '' }}}}
        env: {{ GH_TOKEN: "${{{{ github.token }}}}" }}
        run: gh release download e2-assets --pattern "${{{{ inputs.icon }}}}" --output e2_icon.png --clobber
      - name: Bundle
        shell: pwsh
        run: |
          $icon = @(); if (Test-Path e2_icon.png) {{ $icon = @("--icon", "e2_icon.png") }}
          python -m PyInstaller {args} @icon e2_launch.py
      - name: Zip
        run: Compress-Archive -Path "dist/{app}" -DestinationPath "{app}-${{{{ inputs.version }}}}-windows.zip"
      - name: Upload to a pre-release
        env: {{ GH_TOKEN: "${{{{ github.token }}}}" }}
        run: |
          gh release delete "${{{{ inputs.tag }}}}" --yes --cleanup-tag 2>$null
          gh release create "${{{{ inputs.tag }}}}" "{app}-${{{{ inputs.version }}}}-windows.zip" --prerelease --target "${{{{ inputs.ref }}}}" --title "E2 build ${{{{ inputs.version }}}} (Windows)" --notes "Built by E2 via GitHub Actions"
"""


def install_workflow(ws: Path, cfg_all: dict, app: str) -> Path:
    f = ws / WORKFLOW
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(workflow_yaml(ws, cfg_all["platform"], app))
    return f


async def _pyinstaller_setup(ctx, key, ws: Path, *extra: str) -> dict:
    env = tech.py_env(ws)
    ctx.log(key, "  installing PyInstaller into the project's environment")
    if tech.py_mode(ws) == "uv":
        await ctx.sh(key, "uv", "pip", "install", "-q", "pyinstaller", *extra, cwd=ws, env=env)
    else:
        await ctx.sh(key, "python", "-m", "pip", "install", "-q", "pyinstaller", *extra, cwd=ws, env=env)
    return env


# ── Windows, built on this Windows machine ──
async def build_windows_local(ctx, key, ws: Path, out: Path, app: str) -> list[Path]:
    env = await _pyinstaller_setup(ctx, key, ws, "pillow")  # pillow lets PyInstaller turn the PNG icon into .ico
    b = ws / ".e2build" / "pyapp"
    shutil.rmtree(b, ignore_errors=True)
    b.mkdir(parents=True)
    (b / "launch.py").write_text(launcher(ws, ctx.config["platform"], app), encoding="utf-8")
    icon = icon_source(ws, ctx.config["platform"])
    icon_args = ["--icon", icon] if icon else []
    ctx.log(key, "  bundling Python + all dependencies (large ML libraries make this take a few minutes)")
    await ctx.sh(key, "python", "-m", "PyInstaller", *pyinstaller_args(ws, app), "--distpath", b / "dist", "--workpath", b / "work",
                 "--specpath", b, *icon_args, b / "launch.py", cwd=ws, env=env)
    folder = b / "dist" / app
    if not (folder / f"{app}.exe").exists():
        raise RuntimeError(f"PyInstaller did not produce {app}.exe")
    z = out / f"{app}-{ctx.run['version']}-windows.zip"
    ctx.log(key, "  zipping the app folder")
    shutil.make_archive(str(z.with_suffix("")), "zip", folder.parent, app)
    return [z]


async def build_windows(ctx, key, ws: Path, out: Path, app: str) -> list[Path]:
    if tech.WIN:
        return await build_windows_local(ctx, key, ws, out, app)
    repo = github_repo(ctx.config["source"].get("url", ""))
    if not repo:
        raise RuntimeError("Windows apps are built on GitHub Actions: the Source must be a github.com repository")
    if not tech.has("gh"):
        raise RuntimeError("Install the GitHub CLI and sign in: `brew install gh` then `gh auth login`")
    if not (ws / WORKFLOW).exists():
        raise RuntimeError(f"The repository has no {WORKFLOW}. Use 'Install Windows builder' on this stage's page (one-time)")
    ver, commit = ctx.run["version"], ctx.run["stages"]["source"].get("detail", {}).get("commit") or ctx.config["source"]["branch"]
    tag = f"e2-build-v{ver}"
    icon_name = ""
    icon = icon_source(ws, ctx.config["platform"])
    if icon:  # convert here (svg/icns can't be read on the runner), park it on the 'e2-assets' pre-release
        png = await to_png(ctx, key, icon, ws / ".e2build" / "winicon", 256)
        icon_name = f"e2-icon-{ver}.png"
        shutil.copy2(png, png.with_name(icon_name))
        await ctx.sh(key, "gh", "release", "view", "e2-assets", "--repo", repo, check=False, quiet=True)
        if ctx.last_rc != 0:
            await ctx.sh(key, "gh", "release", "create", "e2-assets", "--repo", repo, "--prerelease", "--title", "E2 build assets",
                         "--notes", "Files E2 hands to its GitHub Actions builds (e.g. the app icon). Safe to ignore.")
        await ctx.sh(key, "gh", "release", "upload", "e2-assets", png.with_name(icon_name), "--repo", repo, "--clobber")
        ctx.log(key, f"  app icon: {icon.name} → {icon_name} (256 px; PyInstaller turns it into .ico on Windows)")
    since = time.time()
    await ctx.sh(key, "gh", "workflow", "run", "e2-windows.yml", "--repo", repo, "--ref", ctx.config["source"]["branch"],
                 "-f", f"version={ver}", "-f", f"ref={commit}", "-f", f"tag={tag}", "-f", f"icon={icon_name}")
    run_id = None
    for _ in range(30):  # the run appears a few seconds after dispatch
        await asyncio.sleep(4)
        js = await ctx.sh(key, "gh", "run", "list", "--repo", repo, "--workflow", "e2-windows.yml", "--limit", "5",
                          "--json", "databaseId,createdAt,event", quiet=True)
        from datetime import datetime
        for r in json.loads(js or "[]"):
            if r["event"] == "workflow_dispatch" and datetime.fromisoformat(r["createdAt"].replace("Z", "+00:00")).timestamp() >= since - 30:
                run_id = r["databaseId"]
                break
        if run_id:
            break
    if not run_id:
        raise RuntimeError("The GitHub Actions run did not start")
    ctx.log(key, f"  GitHub Actions run: https://github.com/{repo}/actions/runs/{run_id}")
    await ctx.sh(key, "gh", "run", "watch", str(run_id), "--repo", repo, "--exit-status", "--interval", "20")
    await ctx.sh(key, "gh", "release", "download", tag, "--repo", repo, "--pattern", "*-windows.zip", "--dir", out, "--clobber")
    files = sorted(out.glob("*-windows.zip"))
    if not files:
        raise RuntimeError("The Windows build finished but its zip was not found on the release")
    return files
